# `EXCLUSION_DEPTH`, `SWITCH_RADIUS` and `SWITCH_WIDTH` are now fields of
# `params.ForceFieldParams` -- `exclusion_depth`, `switch_radius` and
# `switch_width` -- read through `params.resolve()` at call time, as is the
# soft-core constant `soft_core`; see that module for why.


def switch(
    r: np.ndarray, params: ForceFieldParams | None = None
) -> tuple[np.ndarray, np.ndarray]:
    """`g = 1 - 1/(1 + exp((r - rc)/w))`, the mirror image of `zbl.taper`.

    Returns `(g, dg/dr)`.  `g` runs from 0 well inside `switch_radius` to 1 well
    outside it, and `dg/dr = g (1 - g) / w`.

    It is the same functional form as `zbl.taper` reflected, and the same width,
    but **not its complement**: `switch_radius` is 2.2 A where `taper_radius` is
    1.5, so `switch(r) + taper(r)` is not 1 and the two terms leave a gap
    rather than handing straight over.  See `params.ForceFieldParams` for the
    measurement that forces this and for what lives in the gap.

    `params` defaults to the active set -- the dataset's, once a manifest has
    been loaded.  `r` is in Angstrom, as `switch_radius` and `switch_width` are.

    The exponent is clipped for the same reason `zbl.taper` clips it: this is
    evaluated over every pair in the box, including ones half a cell apart, and
    an unclipped `exp` overflows to `inf` and turns `g (1 - g)` into `0 * inf`.
    """
    ff = resolve(params)
    z = np.clip((r - ff.switch_radius) / ff.switch_width, -500.0, 500.0)
    f = 1.0 / (1.0 + np.exp(z))
    return 1.0 - f, f * (1.0 - f) / ff.switch_width


def pair_potential(
    r: np.ndarray,
    sigma: np.ndarray,
    eps: np.ndarray,
    params: ForceFieldParams | None = None,
) -> tuple[np.ndarray, np.ndarray]:
    """Switched soft-core 12-6 and its radial derivative, `(u, du/dr)`.

    This is the potential the force field evaluates, not the textbook 12-6: it
    is multiplied by `switch`, so it is off inside `switch_radius` and on
    outside it.  See the module docstring for why, and
    `params.ForceFieldParams.switch_radius` for where the boundary sits relative
    to `zbl`'s taper radius.

    `r` and `sigma` in Angstrom, because `switch` fixes the length unit; `u`
    comes back in the unit of `eps`, which is eV everywhere it is called.

    Every caller goes through here so the forms can never drift apart -- and
    they must not, because the near-neighbour half of the sum is cancelled by
    `exclusion` terms built from this same form.

    **The 12-6 is soft-cored, and this is not cosmetic.**  With
    `s = c + (r/sigma)**6` and `c = soft_core`,

        u = 4 eps [ s**-2 - s**-1 ]

    which is the textbook 12-6 at `c = 0` and, for `c > 0`, finite everywhere:
    `u(0) = 4 eps (1/c**2 - 1/c)`, 39600 eps at the default 0.01.  The
    decomposition `E = sum_all_pairs - sum_near_pairs` evaluates every *bonded*
    pair in both sums, at a separation where bare 12-6 is enormous.  At
    equilibrium that is merely ugly -- 843 eV cancelling to zero on an H2
    template, with thirteen digits to spare.  On a hot trajectory it is fatal:
    an H2 bond compressed to 0.3 A puts 1e8 eV into both sums, 0.2 A puts in
    1e10, and 0.024 A puts in 1e21.  Measured on the 3000 K probe, the two sums
    reached 1e21 by step 143 and their difference -- the physical energy, of
    order 1e2 -- came back quantized to 2**22 eV.  The forces went with it and
    the box heated to 1e16 K.

    The soft core bounds what a compressed bond can contribute -- under 300 eV
    for the heaviest pair the datasets carry, at any separation -- while being
    smooth rather than merely C1, so the cancellation keeps its precision and
    the gradient stays the gradient.  Where the term does physical work it is
    barely touched: the minimum is still at `s = 2`, so the well depth is
    exactly `eps` and only its position moves, inward by `(1 - c/2)**(1/6)`,
    0.08%; the zero crossing, at `s = 1`, moves inward by 0.17%.  Because both halves come through here, the
    switch cancels exactly on any pair that is excluded, which is every pair it
    can reach.

    A pair with `sigma = 0` has no 12-6 at all, as it had under the bare form,
    and is masked rather than divided by.
    """
    ff = resolve(params)
    has_lj = sigma != 0.0
    x6 = (r / np.where(has_lj, sigma, 1.0)) ** 6
    inv_s = 1.0 / (ff.soft_core + x6)
    inv_s2 = inv_s * inv_s
    u = np.where(has_lj, 4.0 * eps * (inv_s2 - inv_s), 0.0)
    # ds/dr = 6 x6 / r; the r is kept out of the denominator so a pair at
    # exact contact, which the soft core now makes finite, stays finite.
    ds_dr = 6.0 * r**5 / np.where(has_lj, sigma, 1.0) ** 6
    du_dr = np.where(has_lj, 4.0 * eps * (inv_s2 - 2.0 * inv_s2 * inv_s) * ds_dr, 0.0)

    # Product rule, applied here rather than in `__call__` for the reason
    # `zbl.pair_potential` gives: the forces, the virial and
    # fast-forces' `refine`'s curvatures all differentiate whatever this
    # function returns, so the switch and its derivative have to travel
    # together.
    #
    # The soft core above is what makes this well defined at small `r`.  `g`
    # goes to zero there while a bare `r**-12` goes to 1e21, and `0 * 1e21` is
    # not zero in floating point -- it is 1e21 times a denormal and then
    # whatever the compiler feels like.  Bounded by `4 eps / c**2`, the product
    # is a clean underflow to zero.
    g, dg_dr = switch(r, ff)
    return g * u, g * du_dr + dg_dr * u


def near_pairs(graph: nx.Graph, depth: int | None = None) -> set[tuple[int, int]]:
    """Node pairs within `depth` bonds of each other in `graph`, as `(i, j)`, i < j.

    `depth` defaults to the active `exclusion_depth`, resolved here rather than
    in the signature so that a manifest loaded after import is still honoured.
    """
    if depth is None:
        depth = active().exclusion_depth
    pairs: set[tuple[int, int]] = set()
    for node in graph:
        for other, distance in nx.single_source_shortest_path_length(
            graph, node, cutoff=depth
        ).items():
            if distance == 0 or other <= node:
                continue
            pairs.add((node, other))
    return pairs


def global_params(term_dict: dict, natoms: int) -> tuple[np.ndarray, np.ndarray]:
    """A `term_dict`'s per-atom sigma and epsilon, as system-length vectors.

    In global atom order rather than term order.  An atom with no `lennardjones`
    row gets zero for both, which is what `LennardJones.__call__` gives it by
    leaving it out of the sum: a zero sigma is masked in `pair_potential`.
    """
    sigma = np.zeros(natoms)
    eps = np.zeros(natoms)
    params = term_dict.get("lennardjones")
    if params is not None:
        indices = params["atoms"][:, 0]
        sigma[indices] = params["kwargs"]["sigma"]
        eps[indices] = params["kwargs"]["eps"]
    return sigma, eps


def _pair_energies(r, sig_i, eps_i, sig_j, eps_j, ff: ForceFieldParams):
    """`(u, du/dr)` of pairs at `r`: `pair_potential`, cut off if `lj_cutoff` is set.

    Geometric combining of the two atoms' parameters; any shapes that
    broadcast.  Under `lj_cutoff` the pair is switched off over its last
    `lj_cutoff_width` by `cutoff_switch`.
    """
    u, du_dr = pair_potential(r, np.sqrt(sig_i * sig_j), np.sqrt(eps_i * eps_j), ff)
    if ff.lj_cutoff is not None:
        rc = ff.lj_cutoff
        s, ds_dr = cutoff_switch(r, rc - ff.lj_cutoff_width, rc)
        u, du_dr = u * s, du_dr * s + u * ds_dr
    return u, du_dr


def _pair_list(geometry, ff: ForceFieldParams) -> Pairs:
    """The pairs the 12-6 sums: inside `lj_cutoff`, or every pair without one."""
    if ff.lj_cutoff is None:
        return geometry.pairs(None)
    _check_cutoff(ff.lj_cutoff, geometry.pbc, geometry.cell)
    return geometry.pairs(ff.lj_cutoff)


def _has_tail(ff: ForceFieldParams, pbc) -> bool:
    return ff.lj_cutoff is not None and bool(np.all(pbc))


@dataclass
class _Block:
    """One EVB block as the 12-6 sees it.  Block-local columns throughout."""

    atoms: np.ndarray  # (nb,) global indices
    sigma: np.ndarray  # (nstates, nb)
    eps: np.ndarray  # (nstates, nb)
    weights: np.ndarray  # (nstates,)
    varies: bool
    # Computed on first use, for a varying block.  `touch` indexes the pairs
    # with one atom in the block and the other static, `inner` those with both
    # in the block; each one's `(u, du/dr)` per state, `(nstates, npairs)`,
    # with the block's atoms at that state's parameters and every other atom
    # at the static ones.
    touch: np.ndarray | None = None
    touch_u: np.ndarray | None = None
    touch_du: np.ndarray | None = None
    inner: np.ndarray | None = None
    inner_u: np.ndarray | None = None
    inner_du: np.ndarray | None = None
    intra: np.ndarray | None = None  # (nstates,), eV, tail share included
    static_env: np.ndarray | None = None  # (nstates,), eV, tail share included
    # The tail correction's share of `intra + static_env`, if there is one.
    tail: np.ndarray | None = None


class LennardJones:
    """12-6 with geometric combining, over all pairs or the pairs inside `lj_cutoff`.

    Two index spaces meet here, as in `ACKS2`, and confusing them is silent:
    the per-atom parameters arrive in *term order* -- the order the
    `lennardjones` terms were collected -- while `pos` and the returned forces
    are in *global* atom order.  `indices[k]` is the global index of the k-th
    term.  `__call__` builds everything in term order and scatters the forces
    back at the very end; the EVB path below works in global order throughout,
    through `global_params`.

    Combining is geometric in both parameters, matching q-force's
    `A=sqrt(A1*A2); B=sqrt(B1*B2)` -- *not* Lorentz-Berthelot.  Using the
    arithmetic mean for sigma here would silently disagree with
    `compute_exclusion`, and the disagreement would show up only as templates
    no longer reproducing their own energies.

    **Pairs, not matrices.**  Everything here is a sum over a
    `neighbors.Pairs` list -- the pairs inside `lj_cutoff`, from the force
    call's neighbour list, or every pair when there is no cutoff.  Under
    `lj_cutoff` the term is therefore `O(N)` in the atoms; without one it is
    the all-pairs sum it always was.  The tail correction is a sum over every
    ordered pair of atoms, inside the cutoff or not, but it depends only on
    the two atoms' parameters, so it is summed over parameter types (`_tail`,
    `_Tails`) rather than over pairs.

    **Per-state parameters.**  `__call__` is one fixed bonding pattern, which is
    what the fitter and `evaluate.py` want.  `System` drives the same interface
    `PointCharge` exposes instead -- `prepare`, `bind`, `corrections` / `update`
    per block, then `evaluate` -- because each diabatic state takes its sigma and
    epsilon from its own templates, and two templates need not agree on an
    atom.  A block is *varying* if any two of its states disagree on any atom;
    only varying blocks get nonzero corrections, and with none the result is
    `__call__` on the seed topology, operation for operation.

    The states of different blocks are combined as a product of the blocks'
    ground states, the model `PointCharge` uses: a pair inside block A costs
    `sum_s w_s u(p^s, p^s)`, a pair between A and a static atom `sum_s w_s
    u(p_i^s, p_j)`, and a pair between two varying blocks `sum_st w_s w_t
    u(p_i^s, p_j^t)`.  It is the *pair energies* that are averaged and not the
    parameters, because geometric combining makes `u` nonlinear in them -- where
    `PointCharge` may average charges only because Coulomb is bilinear in q.
    The energy is then linear in each block's weights and its derivative with
    respect to them is `corrections`, which is the Hellmann-Feynman condition.
    """

    def __init__(self):
        self._seed = None
        self.geometry = None
        self.natoms = 0
        self.sigma0 = None
        self.eps0 = None
        self.blocks: list[_Block] = []
        self._reset()

    def _reset(self) -> None:
        """Forget everything derived from the blocks."""
        self._list = None
        self._touched = None
        self._slot = None
        self._tails = None
        self._cross: dict[tuple[int, int], tuple[np.ndarray, np.ndarray]] = {}
        self._cross_index: dict[tuple[int, int], np.ndarray] = {}

    def __call__(
        self,
        pos: np.ndarray,
        pbc: np.ndarray,
        cell: np.ndarray,
        term_dict: dict,
        displacements=None,
    ) -> tuple[float, np.ndarray, np.ndarray]:
        """Energy, forces and virial; `displacements` is the force call's
        `neighbors.Geometry`, or `pointcharge.geometry` over every atom, if the
        caller already has it."""
        params = _require(term_dict)
        indices = params["atoms"][:, 0]
        sigma = np.asarray(params["kwargs"]["sigma"], dtype=float)
        eps = np.asarray(params["kwargs"]["eps"], dtype=float)

        # In term order, so the parameter vectors line up with the pairs.
        geometry = as_geometry(displacements, pos, pbc, cell).subset(indices)
        ff = active()
        pairs = _pair_list(geometry, ff)
        i, j = pairs.i, pairs.j
        u, du_dr = _pair_energies(pairs.r, sigma[i], eps[i], sigma[j], eps[j], ff)
        # Each pair once, `i < j`, so no 0.5: `pair_gradients` puts each pair's
        # gradient on both atoms, and under a homogeneous strain `v -> (I + e)
        # v`, so `dr/de_ab = v_a v_b / r`, as `ZBL.__call__` has it.
        energy = float(np.sum(u))
        f_pair, virial = pair_gradients(i, j, du_dr, pairs.v, pairs.r, len(indices))
        forces = np.zeros_like(pos)
        forces[indices] = f_pair
        if _has_tail(ff, pbc):
            rc = ff.lj_cutoff
            volume = abs(np.linalg.det(np.asarray(cell)))
            tail = _tail(sigma, eps, rc - ff.lj_cutoff_width, rc, ff) / volume
            # `E_tail = T / V` and a strain scales `V` by `1 + tr e`.
            energy += tail
            virial = virial - tail * np.eye(3)
        return energy, forces, virial

    # -- the geometry ---------------------------------------------------------

    def prepare(self, pos, pbc, cell, term_dict: dict, displacements=None) -> None:
        """Take the geometry and the seed topology's parameters.

        The seed's parameters are the static ones: every atom outside a varying
        block keeps them.  Nothing is computed until a varying block needs it,
        so a dataset whose templates agree pays exactly what `__call__` costs.
        `displacements` is as `__call__` takes it.
        """
        _require(term_dict)
        self._seed = (pos, pbc, cell, term_dict)
        self.geometry = as_geometry(displacements, pos, pbc, cell)
        self.natoms = len(pos)
        self.sigma0, self.eps0 = global_params(term_dict, self.natoms)
        self.blocks = []
        self._reset()

    def _pairs(self) -> Pairs:
        """The pair list over every atom, in global order."""
        if self._list is None:
            self._list = _pair_list(self.geometry, active())
        return self._list

    def _layout(self):
        """The pairs that touch a varying block, and which block each end is in.

        Returns `(touched, owner_i, owner_j)`: indices into `_pairs()` and the
        varying block of each end, `-1` for a static atom.  Every other pair is
        between static atoms and keeps the static parameters.
        """
        if self._touched is None:
            pairs = self._pairs()
            owner = np.full(self.natoms, -1)
            self._slot = np.zeros(self.natoms, dtype=int)
            for k in self._varying():
                atoms = self.blocks[k].atoms
                owner[atoms] = k
                self._slot[atoms] = np.arange(len(atoms))
            oi, oj = owner[pairs.i], owner[pairs.j]
            touched = np.flatnonzero((oi >= 0) | (oj >= 0))
            self._touched = (touched, oi[touched], oj[touched])
        return self._touched

    # -- the blocks -----------------------------------------------------------

    @property
    def self_consistent(self) -> bool:
        """Whether one block's corrections depend on another block's weights.

        Only when two blocks vary: a varying block's environment is otherwise
        static, and a static block has no corrections at all.
        """
        return sum(block.varies for block in self.blocks) > 1

    def bind(self, blocks) -> None:
        """Read each block's per-state parameters off its states' terms.

        `blocks` are `basis.Block`s, and every state of one spans the same
        atoms.  The static parameters of each block's atoms are restated from
        its seed state, as `PointCharge.bind` restates its charges.
        """
        for block in blocks:
            atoms = np.array(sorted(block.states[0].graph.nodes()), dtype=int)
            sigma = np.empty((block.nstates, len(atoms)))
            eps = np.empty((block.nstates, len(atoms)))
            for s, state in enumerate(block.states):
                sig_s, eps_s = global_params(state.term_dict, self.natoms)
                sigma[s], eps[s] = sig_s[atoms], eps_s[atoms]
            varies = bool(
                np.any(sigma != sigma[:1]) or np.any(eps != eps[:1])
            )
            weights = np.zeros(block.nstates)
            weights[block.seed_index] = 1.0
            self.blocks.append(_Block(atoms, sigma, eps, weights, varies))
            self.sigma0[atoms] = sigma[block.seed_index]
            self.eps0[atoms] = eps[block.seed_index]
        self._reset()

    def _varying(self) -> list[int]:
        return [i for i, block in enumerate(self.blocks) if block.varies]

    def _rows(self, index: int) -> _Block:
        """Block `index`'s per-state pair energies, and its intra-block and static sums."""
        block = self.blocks[index]
        if block.touch is None:
            ff = active()
            pairs = self._pairs()
            touched, oi, oj = self._layout()
            slot = self._slot
            i, j, r = pairs.i[touched], pairs.j[touched], pairs.r[touched]

            inner = (oi == index) & (oj == index)
            si, sj = slot[i[inner]], slot[j[inner]]
            block.inner = touched[inner]
            block.inner_u, block.inner_du = _pair_energies(
                r[inner][None, :],
                block.sigma[:, si],
                block.eps[:, si],
                block.sigma[:, sj],
                block.eps[:, sj],
                ff,
            )

            first = (oi == index) & (oj < 0)
            touch = first | ((oj == index) & (oi < 0))
            mine = np.where(first, i, j)[touch]
            other = np.where(first, j, i)[touch]
            sm = slot[mine]
            block.touch = touched[touch]
            block.touch_u, block.touch_du = _pair_energies(
                r[touch][None, :],
                block.sigma[:, sm],
                block.eps[:, sm],
                self.sigma0[other][None, :],
                self.eps0[other][None, :],
                ff,
            )

            block.intra = np.sum(block.inner_u, axis=1)
            block.static_env = np.sum(block.touch_u, axis=1)
            tails = self._tail_tables()
            if tails is not None:
                intra, static = tails.block(index)
                block.intra = block.intra + intra
                block.static_env = block.static_env + static
                block.tail = intra + static
        return block

    def _cross_pairs(self, a: int, b: int) -> tuple[np.ndarray, np.ndarray]:
        """`(u, du/dr)` between two varying blocks, `(nstates_a, nstates_b, npairs)`.

        Over the pairs `_cross_index[(a, b)]` lists, block `a`'s atom first.
        """
        cached = self._cross.get((a, b))
        if cached is None:
            ff = active()
            A, B = self.blocks[a], self.blocks[b]
            pairs = self._pairs()
            touched, oi, oj = self._layout()
            first = (oi == a) & (oj == b)
            between = first | ((oi == b) & (oj == a))
            i, j = pairs.i[touched], pairs.j[touched]
            sa = self._slot[np.where(first, i, j)[between]]
            sb = self._slot[np.where(first, j, i)[between]]
            r = pairs.r[touched[between]]
            u, du = _pair_energies(
                r[None, None, :],
                A.sigma[:, None, sa],
                A.eps[:, None, sa],
                B.sigma[None, :, sb],
                B.eps[None, :, sb],
                ff,
            )
            index = touched[between]
            cached = self._cross[(a, b)] = (u, du)
            self._cross[(b, a)] = (u.transpose(1, 0, 2), du.transpose(1, 0, 2))
            self._cross_index[(a, b)] = self._cross_index[(b, a)] = index
        return cached

    def _tail_tables(self) -> "_Tails | None":
        """The tail correction by parameter type, if `lj_cutoff` and full periodicity."""
        pos, pbc, cell, _ = self._seed
        ff = active()
        if not _has_tail(ff, pbc):
            return None
        if self._tails is None:
            varying = self._varying()
            static = np.ones(self.natoms, dtype=bool)
            for k in varying:
                static[self.blocks[k].atoms] = False
            self._tails = _Tails(
                self.sigma0,
                self.eps0,
                static,
                {k: self.blocks[k] for k in varying},
                abs(np.linalg.det(np.asarray(cell))),
                ff,
            )
        return self._tails

    def corrections(self, index: int) -> np.ndarray:
        """What each state of block `index` adds to its diagonal, in eV.

        The 12-6 of every pair the block's atoms take part in, at that state's
        parameters, with every other varying block at its current weights.
        Zero on a block whose states agree, since the sum is then the same
        number on all of them and belongs outside the Hamiltonian.
        """
        block = self.blocks[index]
        if not block.varies:
            return np.zeros(len(block.sigma))
        self._rows(index)
        out = block.intra + block.static_env
        tails = self._tail_tables()
        for other in self._varying():
            if other == index:
                continue
            u, _ = self._cross_pairs(index, other)
            cross = np.sum(u, axis=2)
            if tails is not None:
                cross = cross + tails.cross(index, other)
            out = out + cross @ self.blocks[other].weights
        return out

    def update(self, index: int, weights: np.ndarray) -> None:
        """Adopt block `index`'s new ground-state weights."""
        self.blocks[index].weights = np.asarray(weights, dtype=float)

    # -- evaluation -----------------------------------------------------------

    def evaluate(self) -> tuple[float, np.ndarray, np.ndarray]:
        """Energy, forces and virial of the whole system at the current weights.

        The weights are held fixed under the derivative, as in
        `PointCharge.evaluate`, which is exact once `System` has iterated the
        blocks to self-consistency.
        """
        varying = self._varying()
        if not varying:
            return self(*self._seed, displacements=self.geometry)

        ff = active()
        pairs = self._pairs()
        i, j = pairs.i, pairs.j
        s0, e0 = self.sigma0, self.eps0
        u, du_dr = _pair_energies(pairs.r, s0[i], e0[i], s0[j], e0[j], ff)
        # Every pair touching a varying block goes to its weighted states.
        for k in varying:
            block = self._rows(k)
            w = block.weights
            u[block.inner], du_dr[block.inner] = w @ block.inner_u, w @ block.inner_du
            u[block.touch], du_dr[block.touch] = w @ block.touch_u, w @ block.touch_du
        for n, a in enumerate(varying):
            for b in varying[n + 1 :]:
                uc, duc = self._cross_pairs(a, b)
                wa, wb = self.blocks[a].weights, self.blocks[b].weights
                index = self._cross_index[(a, b)]
                u[index] = np.einsum("s,t,stp->p", wa, wb, uc)
                du_dr[index] = np.einsum("s,t,stp->p", wa, wb, duc)
        energy = float(np.sum(u))
        forces, virial = pair_gradients(i, j, du_dr, pairs.v, pairs.r, self.natoms)

        tails = self._tail_tables()
        if tails is not None:
            tail = tails.static
            for k in varying:
                block = self.blocks[k]
                tail += float(block.weights @ block.tail)
            for n, a in enumerate(varying):
                for b in varying[n + 1 :]:
                    wa, wb = self.blocks[a].weights, self.blocks[b].weights
                    tail += float(wa @ tails.cross(a, b) @ wb)
            # `E_tail = T / V` and a strain scales `V` by `1 + tr e`, as in `__call__`.
            energy += tail
            virial = virial - tail * np.eye(3)
        return energy, forces, virial


class _Tails:
    """The tail correction of the per-state path, summed over parameter types.

    `__call__`'s tail is `(1/V) sum_ij t(p_i, p_j)` over every *ordered* pair of
    atoms, self-pairs included, with `t = 2 pi _pair_tail` -- a function of the
    two atoms' parameters alone.  So any part of it is a quadratic form in
    *type counts*: with `T[a, b] = t(type a, type b) / V` and `c_X` the number
    of atoms of each type in a set `X`, the tail between sets `X` and `Y` is
    `c_X^T T c_Y`.  The per-state path needs it split as its pair sums are --
    the static atoms among themselves, each varying block's states within the
    block and against the static atoms, and two blocks' states against each
    other -- and each of those is one such product, with no pair list at all.
    """

    def __init__(self, sigma0, eps0, static, blocks: dict, volume: float, ff):
        rows = [np.stack([sigma0, eps0], axis=1)]
        rows += [np.stack([b.sigma.ravel(), b.eps.ravel()], axis=1) for b in blocks.values()]
        types, inverse = np.unique(np.vstack(rows), axis=0, return_inverse=True)
        inverse = np.asarray(inverse).ravel()
        ntypes = len(types)
        rc = ff.lj_cutoff
        ron = rc - ff.lj_cutoff_width
        T = np.empty((ntypes, ntypes))
        for a, (sa, ea) in enumerate(types):
            for b, (sb, eb) in enumerate(types):
                T[a, b] = _pair_tail(np.sqrt(sa * sb), np.sqrt(ea * eb), ron, rc, ff)
        self.T = 2.0 * np.pi * T / volume
        natoms = len(sigma0)
        static_counts = np.bincount(inverse[:natoms][static], minlength=ntypes)
        self.static_counts = static_counts
        self.static = float(static_counts @ self.T @ static_counts)
        # Per varying block, its type counts in each state, `(nstates, ntypes)`.
        self.counts: dict[int, np.ndarray] = {}
        start = natoms
        for k, block in blocks.items():
            nstates, nb = block.sigma.shape
            kinds = inverse[start : start + nstates * nb].reshape(nstates, nb)
            start += nstates * nb
            counts = np.zeros((nstates, ntypes))
            for s in range(nstates):
                counts[s] = np.bincount(kinds[s], minlength=ntypes)
            self.counts[k] = counts

    def block(self, k: int) -> tuple[np.ndarray, np.ndarray]:
        """Block `k`'s tail per state: within the block, and against the static atoms."""
        C = self.counts[k]
        intra = np.einsum("sa,ab,sb->s", C, self.T, C)
        static = 2.0 * C @ (self.T @ self.static_counts)
        return intra, static

    def cross(self, a: int, b: int) -> np.ndarray:
        """Blocks `a` and `b`'s tail between them, `(nstates_a, nstates_b)`."""
        return 2.0 * self.counts[a] @ self.T @ self.counts[b].T


def _require(term_dict: dict) -> dict:
    params = term_dict.get("lennardjones")
    if params is None:
        raise KeyError(
            "No `lennardjones` parameters set. Every atom needs a sigma and "
            "an epsilon, or the system has no Pauli repulsion and molecules "
            "will interpenetrate."
        )
    return params


def _check_cutoff(rc: float, pbc, cell) -> None:
    """Refuse an `lj_cutoff` the minimum image cannot honour."""
    if np.any(pbc):
        widths = 1.0 / np.linalg.norm(np.linalg.inv(np.asarray(cell)), axis=0)
        if rc > 0.5 * widths[np.asarray(pbc, dtype=bool)].min() + 1e-12:
            raise ValueError(
                f"lj_cutoff {rc} A exceeds half the cell's perpendicular "
                f"width ({0.5 * widths.min():.3f} A): the minimum image would "
                "miss pairs inside it"
            )


def cutoff_switch(r: np.ndarray, ron: float, rc: float):
    """CHARMM's energy switch, 1 inside `ron`, 0 at `rc`, and its derivative.

    `S = (rc^2 - r^2)^2 (rc^2 + 2 r^2 - 3 ron^2) / (rc^2 - ron^2)^3` between
    the two: continuous with its first derivative at both ends, so the energy
    and the forces are.
    """
    r2 = r * r
    denom = (rc * rc - ron * ron) ** 3
    inner, outer = r <= ron, r >= rc
    s = (rc * rc - r2) ** 2 * (rc * rc + 2 * r2 - 3 * ron * ron) / denom
    ds = 12 * r * (rc * rc - r2) * (ron * ron - r2) / denom
    return (
        np.where(inner, 1.0, np.where(outer, 0.0, s)),
        np.where(inner | outer, 0.0, ds),
    )


_TAILS: dict = {}
_PAIR_TAILS: dict = {}


def _tail(sigma, eps, ron, rc, ff) -> float:
    """`V E_tail = 2 pi sum_ab N_a N_b int r^2 u_ab(r) (1 - S(r)) dr`.

    The 12-6 a uniform fluid puts beyond the switch, over every ordered pair of
    atoms, by type: the integrand is `pair_potential` itself, soft core and
    all, so the correction is of the term evaluated rather than of the
    textbook one.  Cached on the composition and the parameters, since a fixed
    set of atoms in any cell has the same `T`.
    """
    types, counts = np.unique(np.stack([sigma, eps], axis=1), axis=0, return_counts=True)
    key = (types.tobytes(), counts.tobytes(), ron, rc, ff)
    if key not in _TAILS:
        total = 0.0
        for a, (sa, ea) in enumerate(types):
            for b, (sb, eb) in enumerate(types):
                sig, ep = np.sqrt(sa * sb), np.sqrt(ea * eb)
                total += counts[a] * counts[b] * _pair_tail(sig, ep, ron, rc, ff)
        _TAILS[key] = 2.0 * np.pi * total
    return _TAILS[key]


def _pair_tail(sig, ep, ron, rc, ff) -> float:
    """`int r^2 u(r) (1 - S(r)) dr` for one combined pair, zero for a masked one."""
    key = (float(sig), float(ep), ron, rc, ff)
    if key not in _PAIR_TAILS:
        if sig == 0.0 or ep == 0.0:
            _PAIR_TAILS[key] = 0.0
        else:
            from scipy.integrate import quad

            def integrand(r, inside):
                u = pair_potential(np.array([r]), sig, ep, ff)[0][0]
                weight = 1.0 - cutoff_switch(np.array([r]), ron, rc)[0][0]
                return r * r * u * (weight if inside else 1.0)

            inner = quad(integrand, ron, rc, args=(True,), epsabs=0, epsrel=1e-12)[0]
            outer = quad(integrand, rc, np.inf, args=(False,), epsabs=0, epsrel=1e-12)[0]
            _PAIR_TAILS[key] = inner + outer
    return _PAIR_TAILS[key]
