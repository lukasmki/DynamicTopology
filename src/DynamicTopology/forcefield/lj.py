"""Switched Lennard-Jones repulsion and dispersion, over every pair or a neighbour list.

**What this term is for.**  `zbl.taper` cuts the screened-nuclear repulsion off
at 1.5 A, which is what let the water dimer bind at all -- and left the model
with no intermolecular wall whatsoever above that radius, and no dispersion
anywhere.  Measured: a 64-water box at ambient density read -7.6 kbar and the
equation-of-state crossing sat near 1250 kg/m**3 against an experimental 997.
Too dense, by a quarter, because nothing stopped the box contracting.  This is
the term that stops it.  It is also the only attraction in the force field that
is not electrostatic.

**Why it was retired, and what changed.**  Not because a 12-6 is wrong, but
because q-force's parameters make it enormous at the separations reactive
chemistry visits.  With `sigma_H = 1.96 A` and `r**-12` hardness, a pair at a
*bond length* is deep inside the core:

    pair  r (A)  what it is              12-6      ZBL
    H-H   0.777  the H2 bond length    504 eV    2.0 eV
    O-H   0.960  the O-H bond length   930 eV    5.4 eV
    O-O   1.210  the O2 bond length   1348 eV   11.6 eV

A fixed-topology force field never notices, because those pairs are always
excluded.  A reactive one does: a diabatic state that has *broken* a bond calls
its two atoms different molecules while they sit at the bond length, and pays
hundreds of eV for it.  Every attempt to strip that penalty made the repulsion
differ between diabatic states, and each failed differently -- stripping it from
the unreacted parent as well let the box fuse at 0.60 A; gating it on the
coupling left a 19 eV plateau across rxn_16's reaction path where a wall was
half-removed; and transition states with close non-bonded contacts came back
with EVB amplitudes of -72 to -108 eV.

Every one of those four descends from the same root: **a pair at a bond length
being charged hundreds of eV, and the charge depending on the topology.**
`lj.switch` removes the root rather than the symptoms, and `pair_potential`'s
soft core bounds what is left.  The term is now 0.0024 eV at an O-H bond and
0.035 eV at O2's, four to five orders of magnitude down, and
at that size there is no penalty worth stripping -- so the **whole-system sum
carries no exclusions**.  That is the property that matters, and it is
structural rather than a tuning: with nothing excluded, this sum is the same
number for every diabatic state of every block, so it adds a common shift to
every EVB diagonal, and a common shift moves `np.linalg.eigh`'s eigenvalue by
exactly that constant while leaving the eigenvectors untouched.
It **cannot** produce a plateau, a spurious coupling amplitude, a pivot
dependence, or a discontinuity at the bimolecular cutoff -- not "does not",
cannot.  Each of the four failures lived in the degree of freedom the switch
removes, which is the same argument `forcefield/zbl.py` makes for itself.

**Per-template parameters.**  That argument holds as long as every template
gives an atom the same sigma and epsilon, which per-element values do.  Once
templates are allowed to disagree -- per-molecule fitting -- the sum is no
longer one number: a state is charged the 12-6 of *its own* templates'
parameters, as its `exclusion` terms already were.  `LennardJones` then puts the
state-dependent part on the diagonal of each block whose states disagree and
keeps the rest outside; see the class docstring.  This is safe now in a way it
was not before the switch, because it is the topology-dependence of a *switched*
term: what differs between two states is a pair energy at a non-bonded
separation, millielectronvolts, and never hundreds of eV at a bond length.

The functions that carried those four attempts -- `reactive_exclusion_weights`,
`fixed_basis_weights`, `exclusion_correction`, `lost_exclusion_correction` --
are gone and are not coming back.

**What it costs.**  The same thing `zbl.taper` cost, and for the same reason.
fast-forces' `refine` solves against `E_QForce + E_nonbonded`, and this term is
now inside `E_nonbonded`, so **every `.jsonl` in every dataset has to be
regenerated by `fast-forces refit` after any change to `switch_radius` or
`switch_width`.**  See `production/density-300K/README.md` for what the refit
came to.

**The decomposition.**  LJ depends on the topology only through exclusions, and
exclusions are local to a molecule, so

    E_LJ(state) = sum_{i<j, far apart along the bonds} u_ij
                = sum_{i<j} u_ij  -  sum_{i<j, near along the bonds} u_ij

The first sum is this class, once for the whole system.  The second is a set of
ordinary per-template `exclusion` terms, which `ReactionSet.load` derives through
`forcefield/exclusions.py` and `QForce.compute_exclusion` evaluates on each
diabat's diagonal -- small, because the switch has already taken the term to
millielectronvolts at a bond length, and built from `pair_potential` below so
the two halves are the same function of the same numbers.

Units are ASE's -- sigma in Angstrom, epsilon in eV -- like every other term,
and as the `.jsonl` stores them.  q-force states them in nm and kJ/mol, and
`io/units.py` converts them once, when fast-forces imports its XML.
"""

from dataclasses import dataclass

import networkx as nx
import numpy as np

